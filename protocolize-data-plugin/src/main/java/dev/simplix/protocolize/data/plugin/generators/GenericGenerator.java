package dev.simplix.protocolize.data.plugin.generators;

import dev.simplix.protocolize.data.plugin.generator.Generator;
import dev.simplix.protocolize.data.registries.GenericRegistry;
import lombok.Getter;

import javax.lang.model.SourceVersion;
import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * Date: 23.08.2021
 *
 * @author Exceptionflug
 */
public class GenericGenerator implements Generator {

    private static final String PACKAGE = "dev.simplix.protocolize.data";

    private final File outputDirectory;
    @Getter
    private final String name;
    private final List<GenericRegistry> registries;

    public GenericGenerator(File outputDirectory, GenericRegistry registry, String name) {
        this.outputDirectory = outputDirectory;
        this.registries = Collections.singletonList(registry);
        this.name = name;
    }

    public GenericGenerator(File outputDirectory, List<GenericRegistry> registries, String name) {
        this.outputDirectory = outputDirectory;
        this.registries = registries;
        this.name = name;
    }

    @Override
    public void generate() throws Exception {
        List<String> keys = new ArrayList<>();
        for(GenericRegistry registry : registries) {
            for(String type : registry.entries().keySet()){
                if(!keys.contains(type)){
                    keys.add(type);
                }
            }
        }
        keys.sort(String::compareTo);
        List<String> constants = keys.stream()
            .map(s -> s.substring("minecraft:".length()).replace(".", "_").replace("/", "_").toUpperCase(Locale.ROOT))
            .collect(Collectors.toList());
        validate(constants);

        File packageDirectory = new File(outputDirectory, PACKAGE.replace('.', File.separatorChar));
        Files.createDirectories(packageDirectory.toPath());
        Files.write(new File(packageDirectory, name + ".java").toPath(),
            source(constants).getBytes(StandardCharsets.UTF_8));
    }

    private void validate(List<String> constants) {
        Set<String> seen = new HashSet<>();
        for (String constant : constants) {
            if (!SourceVersion.isIdentifier(constant)) {
                throw new IllegalStateException(name + ": '" + constant + "' is not a valid Java identifier");
            }
            if (!seen.add(constant)) {
                throw new IllegalStateException(name + ": duplicate constant '" + constant + "'");
            }
        }
    }

    private String source(List<String> constants) {
        return "package " + PACKAGE + ";\n"
            + "\n"
            + "// Generated by protocolize-data-plugin. Do not edit by hand.\n"
            + "public enum " + name + " {\n"
            + "    " + String.join(",\n    ", constants) + ";\n"
            + "}\n";
    }

}
